from langchain_core.prompts import PromptTemplate

EDGE_CASE_GENERATOR_PROMPT = PromptTemplate.from_template(
    """You are a software testing expert responsible for generating candidate edge cases.

    Below is a Python function and a description of what it should do.
    Generate a set of candidate edge cases that could expose bugs in the implementation.

    Function:
    {function_code}

    Description:
    {description}

    Rules:

    1. Read the function signature and description carefully. Identify the parameters,
    their defaults, documented behaviors, boundaries, and documented error conditions.

    2. Generate up to 10 candidate edge cases. Be slightly creative and explore
    different meaningful inputs, but stay strictly within the behavior defined by
    the description.

    3. Consider relevant cases such as but not limited to:
    - empty or minimal inputs
    - boundary values
    - values exactly at, just below, or just above documented boundaries
    - zero or negative values when applicable
    - optional parameters omitted to use their defaults
    - meaningful non-default values for optional parameters
    - special strings or characters
    - repeated values
    - parameter combinations that interact in interesting ways

    4. Do NOT blindly apply a generic edge-case checklist. Only generate cases that
    make sense for THIS function.

    5. Do NOT invent behavior. If the description does not define what should happen
    for None, wrong argument types, invalid values, or another unusual input,
    do not generate that case.

    6. The expected result must come ONLY from the description, NEVER from the current
    implementation. If the implementation disagrees with the description, use the
    description's behavior as the expected result. These tests are intended to
    expose implementation bugs.

    7. If a parameter has a default value, try to include at least one meaningful case
    where that parameter is omitted entirely.

    8. If a parameter has a default value, try to include at least one meaningful case
    where you change the default parameter to a new value of the same type.

    9. Use real Python semantics when determining expected results. Do not assume an
    operation raises an exception if Python actually allows it, unless the
    description explicitly requires an exception.

    10. At this stage, prioritize coverage and useful candidate ideas over perfect
    deduplication. You may generate multiple candidates that appear similar;
    the reviewer will remove redundant cases later.

    11. Do not create ordinary, uninteresting inputs unless they are necessary to
        establish an important boundary or behavior.

    How to write each case:

    12. "call" must be one valid Python call expression using the function's name
        and arguments in the order of the function signature.

    13. "expected" MUST always be null. Do not compute return values. A later step
        computes them by running code.

    14. "expected_exception" MUST contain the exception class name only when the
        description explicitly specifies that the call raises that exception.
        Otherwise it MUST be null.

    15. "reason" must be one or two sentences explaining why the case is useful and
        which documented behavior it targets. Do not include arithmetic or computed
        results.

    Output format:

    16. Return one JSON object containing the candidate cases.

    17. Inside "call" and "expected", write normal Python source code. Everything
        outside those strings must be valid JSON.

    {format_instructions}
    """
)


EDGE_CASE_REVIEWER_PROMPT = PromptTemplate.from_template(
    """You are a strict software testing reviewer.

    Below is a Python function, its behavioral description, and candidate edge cases
    generated by another model.

    Your job is to independently review every candidate and return only the strongest,
    valid, relevant, non-redundant test cases. You do NOT compute expected return values.
    A later step does that by running code.

    Function:
    {function_code}

    Description:
    {description}

    Candidate cases:
    {candidate_cases}

    Rules:

    1. Treat EVERY candidate as untrusted. Do not assume the generator is correct.

    2. Verify that every "call" is a valid Python call to the function and that its
    arguments match the function signature.

    3. Independently determine the expected behavior from the DESCRIPTION.
    Never use the current implementation as the source of truth.

    4. If the implementation and description disagree, the description is authoritative.
    Keep the test if it exposes that disagreement.

    5. "expected" MUST always be null. Do not compute, copy or correct return values.

    6. For boundary cases, check the actual input values against the documented boundary
    rather than relying on labels such as "just above", "just below", "exactly", or
    "boundary". Verify that the input really satisfies the claimed relationship.

    Checking and filtering:

    7. Verify "expected_exception". Only keep an exception expectation when the
    description explicitly specifies that the input should raise that exception.

    8. Reject candidates whose behavior is not defined by the description. In particular,
    do not invent errors for None, wrong types, invalid values, or other inputs unless
    the description specifies their behavior.

    9. Detect duplicate calls and remove duplicates.

    10. Detect redundant cases. Two cases can have different inputs but still be redundant
    if they test the same behavior, boundary, or bug. Keep the strongest representative
    unless the cases exercise a meaningful parameter interaction.

    11. Check optional/default parameters carefully. If a parameter has a default value,
    preserve at least one meaningful case where that parameter is actually omitted,
    when such a case is useful and distinct.

    12. Prefer a smaller set of strong tests over a larger set containing redundant tests.

    13. Return at most 8 final cases. Do not add cases merely to reach a target number.

    14. Every final case must be capable of detecting a meaningful bug that the other
    final cases would not detect.

    15. Rewrite the "reason" when necessary so that it accurately explains why the
    test is useful and which part of the description it targets. It must not contain
    arithmetic or computed results.

    Final review before answering:

    16. For every remaining case, perform this complete check:
        - Is the call valid?
        - Is the input relevant?
        - Is the behavior defined by the description?
        - Which rule or condition in the description applies?
        - Is the exception correct according to the description?
        - Is "expected" null?
        - Is this case meaningfully different from the others?

    17. Remove any case that fails any of these checks.

    Output format:

    18. Return ONLY one JSON object containing the final reviewed cases.

    19. Inside "call" and "expected", write normal Python source code. Everything outside
    those strings must be valid JSON.

    {format_instructions}
    """
)


REFERENCE_FUNCTION_PROMPT = PromptTemplate.from_template(
    """You are a careful Python programmer. Your job is to write one reference
    implementation of a function, using ONLY its description. The implementation will be
    run on many inputs to produce the correct expected results.

    Description of the function:
    {description}

    Signature of the function:
    {function_signature}

    Rules:

    1. Implement exactly what the description says and nothing else. Do NOT invent
    numbers, thresholds, rules or behavior that the description does not state.

    2. Use the exact function name and the exact parameter names and order from the
    signature. If a parameter has a default value, use the description's default when it
    states one, and the signature's default otherwise.

    3. Raise exactly the exceptions the description specifies, with exactly the exception
    types it names, under exactly the conditions it names.

    4. Write the rules of the description as real logic (conditions, arithmetic, loops,
    rounding, string and list operations). Never hardcode answers for particular inputs.

    5. Use real Python semantics. Return the same types the description implies, keeping
    floats as floats and integers as integers. If the description names a rounding method,
    follow it exactly.

    6. Use only the Python standard library.

    7. Do not print anything, do not read input, files or the network, and do not call the
    function yourself.

    Output format:

    8. Return exactly one fenced Python code block that contains the function and nothing
    else. No explanation before or after it. It follows this shape:

```python
    def <function name>(<parameters>):
        <code that implements the description>
```
    """
)


